def marginal_tax_for(country):
    """Devuelve (tasa, nota). Si el país no figura o no se informó, usa 25 % y lo avisa."""
    name = (country or "").strip()
    if not name:
        return DEFAULT_TAX, "País no informado: tasa marginal de impuestos 25 % (supuesto)."
    key = ALIASES.get(name, name)
    if key not in TAX:
        return DEFAULT_TAX, f"{name} no figura en la tabla de impuestos de Damodaran: se usa 25 % (supuesto)."
    return TAX[key], f"{name}: {TAX[key]:.2%} (tasa marginal, {SOURCE})."

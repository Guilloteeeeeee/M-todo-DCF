def get_multiples(name):
    """Devuelve dict(n, ev_ebitdard, ev_ebitda) para la industria, o None si no hay (bancos, industria desconocida)."""
    row = MULT.get(name or "")
    if not row:
        return None
    n, rd, eb = row
    return dict(n=n, ev_ebitdard=rd, ev_ebitda=eb)


